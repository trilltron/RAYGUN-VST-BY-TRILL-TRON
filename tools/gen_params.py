import sys,os; sys.path.insert(0,os.path.dirname(__file__))
from params_def import *
def esc(s): return s.replace('"','\\"')
out=['// GENERATED by tools/gen_params.py -- do not edit','#pragma once','namespace rg {',
'enum Kind{KF,KI,KC,KB}; enum Skew{SLin,SLog,SSq};',
'struct PDef{const char* id; const char* name; Kind kind; float mn,mx,def; Skew skew; const char* choices;};']
def row(p):
    id,name,kind,mn,mx,d,x=p; k={'f':'KF','i':'KI','c':'KC','b':'KB'}[kind]
    sk='SLog' if x=='log' else 'SSq' if x=='sq' else 'SLin'
    ch='"'+'|'.join(x)+'"' if isinstance(x,list) else '""'
    return f'{{"{id}","{esc(name)}",{k},{float(mn)!r}f,{float(mx)!r}f,{float(d)!r}f,{sk},{ch}}}'
out.append(f'inline constexpr int NLAYER={len(LAYER)};')
out.append('inline constexpr PDef LAYER_DEFS[NLAYER]={'+',\n'.join(row(p) for p in LAYER)+'};')
out.append(f'inline constexpr int NGLOBAL={len(G)};')
out.append('inline constexpr PDef GLOBAL_DEFS[NGLOBAL]={'+',\n'.join(row(p) for p in G)+'};')
out.append('enum LP{'+','.join('P_'+p[0].upper() for p in LAYER)+',P_COUNT};')
out.append('enum GP{'+','.join('G_'+p[0].upper() for p in G)+',G_COUNT};')
out.append('inline constexpr int NTABLES=%d;'%len(TABLES))
out.append('inline constexpr const char* TABLE_FILES[NTABLES]={'+','.join('"%s"'%t for t in TABLE_IDS)+'};')
out.append('inline constexpr const char* TABLE_NAMES[NTABLES]={'+','.join('"%s"'%t for t in TABLES)+'};')
out.append('inline constexpr const char* MACRO_NAMES[8]={'+','.join('"%s"'%t for t in MACROS)+'};')
out.append('}')
open('Source/ParamTable.h','w').write('\n'.join(out)+'\n')
print(len(LAYER),'layer params,',len(G),'global')
